-- ── Structure Consultant Team ───────────────────────────────────────────────
CREATE TABLE project_did_structure_consultant_team (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technical_master_id    BIGINT       NOT NULL,
    structural_consultancy VARCHAR(200),
    created_date           TIMESTAMP    NOT NULL,
    created_by             BIGINT,
    updated_by             BIGINT,
    updated_date           TIMESTAMP,
    CONSTRAINT fk_did_structure_team_master FOREIGN KEY (technical_master_id)
        REFERENCES project_technical_master (id),
    CONSTRAINT uq_did_structure_team_master UNIQUE (technical_master_id)
);

-- ── Contacts — shared row shape across Client / Architect / Structure ──────
CREATE TABLE project_did_contact (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technical_master_id  BIGINT       NOT NULL,
    party_type           VARCHAR(20)  NOT NULL,
    designation          VARCHAR(100),
    name                 VARCHAR(100),
    mail_id              VARCHAR(150),
    contact_no           VARCHAR(30),
    is_default_row       BOOLEAN      NOT NULL DEFAULT FALSE,
    contact_order        INT          NOT NULL DEFAULT 0,
    created_date         TIMESTAMP    NOT NULL,
    created_by           BIGINT,
    updated_by           BIGINT,
    updated_date         TIMESTAMP,
    CONSTRAINT fk_did_contact_master FOREIGN KEY (technical_master_id)
        REFERENCES project_technical_master (id),
    CONSTRAINT ck_did_contact_party_type CHECK (party_type IN ('CLIENT', 'ARCHITECT', 'STRUCTURE'))
);
CREATE INDEX idx_did_contact_master_party ON project_did_contact (technical_master_id, party_type);
